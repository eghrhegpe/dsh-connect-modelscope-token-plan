// update-host-range.mjs —— 从公共注册表重算 test/host-range.golden.json。
//
// 用法：node tools/update-host-range.mjs           # 写 golden
//       node tools/update-host-range.mjs --check   # 只打印 diff，不写
//
// ## 为什么是生成器，而不是门禁里直接联网
//
// 门禁必须能在干净检出、不装任何东西、不联网的前提下跑（本仓库的离线套件全是
// 这个前提，CI 的 offline job 也不联网装注册表）。所以版本宇宙被冻结进一个入库
// 的 JSON，**只有这个脚本碰网络**。生成器与门禁共用 test/host-range.mjs，写的人
// 与查的人不可能各用一套算术。
//
// ## 为什么宇宙是 @deepseek-ai/dsh，而不是每个 peer 包自己
//
// 因为宿主不是拿 peer 包的版本来判范围——它拿**自己的运行时版本**判：
//
//   dsh-app-boot/lib/index.js
//   semver.satisfies(runtimeVersion, range, { includePrerelease: true })
//
// `@deepseek-ai/dsh-settings@0.1.2-alpha.3` 是那个包的发布节奏，与任何会加载本
// 插件的宿主无关。peer 范围一生只会遇到 DSH 运行时版本，所以那就是唯一的宇宙。
//
// ## 红了是什么意思（以及不是什么）
//
// `verdicts-moved` 表示上游发了一个运行时版本，它相对入库范围的归属与记录不同。
// 这是**版本宇宙的事实**，不是「插件在它上面坏了」的证据：它说的是「范围与世界
// 脱节了，来定夺」。真装真启是另一档（见 docs/TESTING.md），这个门禁不是安装测试。
import { execSync } from "node:child_process";
import { readFileSync, writeFileSync } from "node:fs";
import { fileURLToPath } from "node:url";
import { hostPeers, partition, sortVersions } from "../test/host-range.mjs";

const REPO_ROOT = fileURLToPath(new URL("../", import.meta.url));
const GOLDEN = `${REPO_ROOT}test/host-range.golden.json`;
const UNIVERSE_PACKAGE = "@deepseek-ai/dsh";
const checkOnly = process.argv.includes("--check");

// npm view <pkg> versions --json —— 全部已发布版本，含预发布。
//
// Windows 上 npm 是 .cmd 垫片，execFileSync 不带 shell 会 spawnSync ENOENT
// (errno -4058)；带 {shell:true} 则在 Node 24 触发 DEP0190。execSync 走命令串，
// 而包名是本文件的常量、没有用户输入能到命令行，所以这里安全。
function fetchVersions(packageName) {
  const raw = execSync(`npm view ${packageName} versions --json`, {
    encoding: "utf8",
    // npm 把告警写 stderr，只有 stdout 是 JSON。
    stdio: ["ignore", "pipe", "inherit"],
  });
  const parsed = JSON.parse(raw);
  // 只有一个版本时 npm 返回裸字符串而不是数组。
  return sortVersions(Array.isArray(parsed) ? parsed : [parsed]);
}

// 本插件**实际跑过**的 DSH 运行时版本。
//
// 刻意不读本机——那会让 golden 在开发机与 CI 上不同，而随机器变的黄金表没人能
// review。在一个版本上验证过就加进来，并写清证据在哪。
//
//   0.2.1-rc.2  本机全局 `dsh` CLI 的版本，也是 CI 里
//               `npm install -g @deepseek-ai/dsh` 装到的 dist-tag latest；
//               离线套件、build-gate 与 e2e 都在它上面跑
//
// 加版本前先问：哪个 job / 哪次实测证明本插件在它上面跑起来了？没有证据就不加，
// 这一行是账本，不是愿望清单。
const VALIDATED_ON = ["0.2.1-rc.2"];

const manifest = JSON.parse(readFileSync(`${REPO_ROOT}package.json`, "utf8"));
const universe = fetchVersions(UNIVERSE_PACKAGE);
if (universe.length === 0) throw new Error(`${UNIVERSE_PACKAGE} returned no versions`);

for (const version of VALIDATED_ON) {
  if (!universe.includes(version)) {
    // 故意吵：一个悄悄从注册表消失的版本，意味着上面那条证据指向了空气。
    console.error(`WARNING: validatedOn ${version} 已不在已发布宇宙里`);
  }
}

const peers = {};
for (const [name, range] of hostPeers(manifest)) {
  const { admitted } = partition(universe, range);
  peers[name] = { range, admitted };
}

const golden = {
  $comment: [
    "GENERATED by tools/update-host-range.mjs — 不要手改。",
    "",
    "universe:    已发布的全部 @deepseek-ai/dsh 版本，按 semver 升序。",
    "validatedOn: 本插件真正跑过的运行时版本。",
    "peers:       来自 package.json 的每条 host peer 范围，以及宿主会接受的那个子集。",
    "",
    "test/host-range.test.mjs 红了表示版本宇宙或某条范围动了：重跑生成器并 review",
    "diff——一个版本离开 admitted，要么是范围该放宽，要么是这条宿主线本插件确实放弃。",
    "两者都不是靠手改这个文件来决定的。",
  ],
  universePackage: UNIVERSE_PACKAGE,
  universe,
  validatedOn: VALIDATED_ON,
  peers,
};

const serialized = `${JSON.stringify(golden, null, 2)}\n`;

if (checkOnly) {
  let current = null;
  try {
    current = readFileSync(GOLDEN, "utf8");
  } catch {
    console.error(`${GOLDEN} 还不存在`);
    process.exitCode = 1;
  }
  if (current !== null) {
    if (current === serialized) {
      console.log(`golden 是最新的（${universe.length} 个版本，${Object.keys(peers).length} 条 peer）`);
    } else {
      const before = JSON.parse(current);
      const added = universe.filter((v) => !before.universe.includes(v));
      const removed = before.universe.filter((v) => !universe.includes(v));
      for (const v of added) console.log(`+ universe ${v}`);
      for (const v of removed) console.log(`- universe ${v}`);
      for (const [name, entry] of Object.entries(peers)) {
        const prior = before.peers?.[name];
        if (!prior) {
          console.log(`+ peer ${name} "${entry.range}" (new)`);
          continue;
        }
        if (prior.range !== entry.range) console.log(`~ peer ${name} range ${prior.range} -> ${entry.range}`);
        for (const v of entry.admitted.filter((x) => !prior.admitted.includes(x))) console.log(`+ ${name} admits ${v}`);
        for (const v of prior.admitted.filter((x) => !entry.admitted.includes(x))) console.log(`- ${name} refuses ${v}`);
      }
      console.error("golden 已过期 STALE — 去掉 --check 重跑即可重写");
      process.exitCode = 1;
    }
  }
} else {
  writeFileSync(GOLDEN, serialized);
  console.log(`wrote ${GOLDEN}: ${universe.length} 个版本，${Object.keys(peers).length} 条 peer`);
  for (const [name, entry] of Object.entries(peers)) {
    console.log(`  ${name.padEnd(42)} ${String(entry.admitted.length).padStart(2)}/${universe.length}  ${entry.range}`);
  }
}
